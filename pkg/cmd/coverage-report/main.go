package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type coverage struct{ total, covered int }

func main() {
	profile := flag.String("profile", "build/coverage.out", "Go coverage profile")
	output := flag.String("output", "COVERAGE.md", "Markdown report")
	flag.Parse()
	if err := report(*profile, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func report(profile, output string) error {
	input, err := os.Open(profile)
	if err != nil {
		return err
	}
	defer input.Close()
	groups := make(map[string]coverage)
	scanner := bufio.NewScanner(input)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "mode:") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 3 {
			return fmt.Errorf("invalid coverage line %q", line)
		}
		colon := strings.Index(fields[0], ":")
		if colon < 0 {
			return fmt.Errorf("coverage location has no colon: %q", fields[0])
		}
		statements, err := strconv.Atoi(fields[1])
		if err != nil {
			return err
		}
		count, err := strconv.Atoi(fields[2])
		if err != nil {
			return err
		}
		group := coverageGroup(filepath.Base(fields[0][:colon]), fields[0][:colon])
		value := groups[group]
		value.total += statements
		if count > 0 {
			value.covered += statements
		}
		groups[group] = value
	}
	if err = scanner.Err(); err != nil {
		return err
	}
	names := make([]string, 0, len(groups))
	for name := range groups {
		names = append(names, name)
	}
	sort.Strings(names)
	var document strings.Builder
	document.WriteString("# Go subsystem coverage\n\nGenerated by `make coverage`; statement coverage is grouped by production source responsibility.\n\n| Subsystem | Covered | Statements | Coverage |\n| --- | ---: | ---: | ---: |\n")
	for _, name := range names {
		value := groups[name]
		percentage := 0.0
		if value.total > 0 {
			percentage = 100 * float64(value.covered) / float64(value.total)
		}
		fmt.Fprintf(&document, "| %s | %d | %d | %.1f%% |\n", name, value.covered, value.total, percentage)
	}
	return os.WriteFile(output, []byte(document.String()), 0o644)
}

func coverageGroup(base, path string) string {
	if strings.Contains(path, "/cmd/apalache/") {
		return "CLI and configuration"
	}
	if strings.Contains(base, "json_rpc") || strings.Contains(base, "exploration_service") {
		return "JSON-RPC services"
	}
	if strings.HasPrefix(base, "frontend") || strings.Contains(base, "annotation") {
		return "Frontend and annotations"
	}
	if strings.HasPrefix(base, "ir_") || strings.HasPrefix(base, "types_") || base == "operator.go" {
		return "IR and types"
	}
	for _, prefix := range []string{"smt", "arena", "rewrite", "transition_executor", "bounded_checker", "simulator", "model_decoder"} {
		if strings.HasPrefix(base, prefix) {
			return "Symbolic checker"
		}
	}
	for _, prefix := range []string{"preprocess", "assignments", "configuration", "safety_pipeline", "temporal", "retla", "vmt"} {
		if strings.HasPrefix(base, prefix) {
			return "Passes and preprocessing"
		}
	}
	for _, prefix := range []string{"itf", "tla_format", "tlc_config", "trace_evaluator"} {
		if strings.HasPrefix(base, prefix) {
			return "I/O and traces"
		}
	}
	return "Core support"
}
